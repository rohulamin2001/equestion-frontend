/**
 * Checks if a subject or subject string represents English
 */
export function isEnglishSubject(subjectOrName) {
  if (!subjectOrName) return false;
  if (typeof subjectOrName === "string") {
    const s = subjectOrName.toLowerCase();
    return (
      s.includes("english") || s.includes("ইংরেজি") || s.includes("ইংরেজী")
    );
  }
  const name = (
    subjectOrName.subjectName ||
    subjectOrName.name ||
    ""
  ).toLowerCase();
  const version = (subjectOrName.version || "").toLowerCase();
  return (
    name.includes("english") ||
    name.includes("ইংরেজি") ||
    name.includes("ইংরেজী") ||
    version === "english"
  );
}

/**
 * Returns contextual display name for category based on subject (English vs Bangla)
 */
export function getCategoryDisplayName(catValue, subjectOrIsEnglish = false) {
  if (!catValue) return "";
  const found = CATEGORIES_MAP.find((c) => c.value === catValue);
  const useEnglish =
    typeof subjectOrIsEnglish === "boolean"
      ? subjectOrIsEnglish
      : isEnglishSubject(subjectOrIsEnglish);

  if (!found) return catValue;
  if (useEnglish && found.englishLabel) {
    return found.englishLabel;
  }
  return found.label || catValue;
}
